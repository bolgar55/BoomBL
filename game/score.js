// game/score.js
// Подсчёт очков за ход и серия комбо (spec §Решения 2).
// Формула: +1 очко за каждую занятую клетку при постановке; очистка линий —
// 10×N² очков, где N — число линий, очищенных этим ходом; итог умножается
// на (1 + 0.1×серия), с округлением вниз.
//
// Серия комбо (R05.6): растёт на каждом ходе, который очищает хоть одну
// линию, и НЕ сбрасывается сама по себе ходом без очистки (раньше сбрасывала)
// — ход без очистки просто не меняет серию. Единственный способ обнулить
// серию — истечение времени между ходами: вызывающий код (app.js) сам ведёт
// таймер бездействия и зовёт expireCombo(), если игрок долго не ходит.
// Модуль не знает про время — он только хранит число и решает, начислять ли
// его; таймер — обвязка приложения, не игровое правило само по себе.

export class Score {
  constructor() {
    // Длина текущей серии ходов, очистивших хотя бы одну линию — считая и
    // ходы без очистки между ними, пока игрок не бездействовал слишком долго
    // (см. expireCombo). Формула начисления — деталь модуля, наружу торчит
    // только addMove/expireCombo/reset.
    this.comboStreak = 0;
  }

  /**
   * Начисляет очки за один ход. Серия комбо растёт при очистке линии(й) и
   * остаётся как есть при ходе без очистки — сбросить её может только
   * expireCombo() (таймер бездействия на стороне вызывающего кода).
   * @param {{cellsPlaced: number, linesCleared: number}} move
   * @returns {{points: number, comboStreak: number}}
   */
  addMove({ cellsPlaced, linesCleared }) {
    const placementPoints = cellsPlaced;
    const linePoints = linesCleared > 0 ? 10 * linesCleared * linesCleared : 0;

    if (linesCleared > 0) {
      this.comboStreak += 1;
    }

    const multiplier = 1 + 0.1 * this.comboStreak;
    const points = Math.floor((placementPoints + linePoints) * multiplier);

    return { points, comboStreak: this.comboStreak };
  }

  /**
   * Обнуляет серию комбо из-за нарушения её условия — сейчас единственное
   * условие: игрок не сделал следующий ход достаточно долго (таймер ведёт
   * app.js). Отдельно от addMove, потому что это не результат хода, а его
   * отсутствия.
   * @returns {boolean} true, если серия действительно была ненулевой (есть что показать/скрыть в UI)
   */
  expireCombo() {
    const hadStreak = this.comboStreak > 0;
    this.comboStreak = 0;
    return hadStreak;
  }

  /** Сбрасывает серию комбо (используется при старте новой партии). */
  reset() {
    this.comboStreak = 0;
  }
}
